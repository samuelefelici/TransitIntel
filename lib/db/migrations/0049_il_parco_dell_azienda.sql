-- 0049 — Il parco dell'azienda nel canale dell'AVM (tappa 6.21)
-- ────────────────────────────────────────────────────────────────────────
-- Il flusso SIRI dell'AVM chiama le vetture con un numero: per le vetture
-- dell'azienda la matricola (vetture-azienda.ts, tappa 6.5), per le
-- consorziate un numero di cinque cifre in cui le prime due sostituiscono la
-- sigla dell'azienda e le altre tre sono il progressivo (10003 → SA003). Le
-- regole e l'anagrafica dei mezzi (l'export «Dettaglio veicoli»
-- dell'officina, codice e descrizione) erano scritte nel codice
-- (lib/parco-anagrafica.ts). Qui diventano dati dell'azienda:
--   parco_vetture      l'anagrafica: codice del mezzo, descrizione, ordine
--                      dell'export, quando è stata importata e da chi;
--   parco_consorziate  per prefisso SIRI, le sigle possibili e se le tre
--                      cifre finali sono il progressivo del codice;
--   parco_eccezioni    le matricole che non seguono la regola, una per una.
-- L'anagrafica la sostituisce l'amministratore importando l'export; prefissi
-- ed eccezioni si scrivono in Amministrazione → Azienda → AVM.
-- Per Conerobus entrano i valori che erano nel codice (export di ottobre
-- 2026, confronto del 6/10/2026). Un'installazione nuova parte vuota: le
-- vetture del canale sono tutte dell'azienda, e senza descrizione.
-- ════════════════════════════════════════════════════════════════════════
DO $parco$
BEGIN
  IF pg_catalog.to_regclass('public.parco_vetture') IS NULL THEN
    CREATE TABLE public.parco_vetture (
      codice        text PRIMARY KEY CONSTRAINT parco_vetture_codice CHECK (codice ~ '^[A-Z0-9_.-]{1,20}$'),
      descrizione   text NOT NULL CONSTRAINT parco_vetture_descrizione CHECK (char_length(descrizione) <= 200 AND descrizione !~ '[[:cntrl:]]'),
      ordine        integer NOT NULL CONSTRAINT parco_vetture_ordine CHECK (ordine BETWEEN 1 AND 100000),
      importata_il  timestamptz NOT NULL DEFAULT now(),
      importata_da  uuid REFERENCES public.users(id) ON DELETE SET NULL
    );
  END IF;
  IF pg_catalog.to_regclass('public.parco_consorziate') IS NULL THEN
    CREATE TABLE public.parco_consorziate (
      prefisso      text PRIMARY KEY CONSTRAINT parco_consorziate_prefisso CHECK (prefisso ~ '^[0-9]{2}$'),
      -- le sigle dei codici dell'officina per quel prefisso (si controllano nell'API)
      sigle         text[] NOT NULL,
      -- le tre cifre finali sono il progressivo del codice (10003 → SA003); no: solo le eccezioni
      a_progressivo boolean NOT NULL DEFAULT true,
      ordine        integer NOT NULL DEFAULT 0 CONSTRAINT parco_consorziate_ordine CHECK (ordine BETWEEN 0 AND 999),
      aggiornata_il timestamptz NOT NULL DEFAULT now()
    );
  END IF;
  IF pg_catalog.to_regclass('public.parco_eccezioni') IS NULL THEN
    CREATE TABLE public.parco_eccezioni (
      siri_ref      text PRIMARY KEY CONSTRAINT parco_eccezioni_siri_ref CHECK (siri_ref ~ '^[0-9]{1,10}$'),
      codice        text NOT NULL CONSTRAINT parco_eccezioni_codice CHECK (codice ~ '^[A-Z0-9_.-]{1,20}$'),
      nota          text NOT NULL DEFAULT '' CONSTRAINT parco_eccezioni_nota CHECK (char_length(nota) <= 300 AND nota !~ '[[:cntrl:]]'),
      aggiornata_il timestamptz NOT NULL DEFAULT now()
    );
  END IF;
  IF pg_catalog.to_regrole('cerbero_owner') IS NOT NULL THEN
    ALTER TABLE public.parco_vetture OWNER TO cerbero_owner;
    ALTER TABLE public.parco_consorziate OWNER TO cerbero_owner;
    ALTER TABLE public.parco_eccezioni OWNER TO cerbero_owner;
  END IF;
END $parco$;
